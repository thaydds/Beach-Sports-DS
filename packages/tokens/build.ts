import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import type { TransformedToken } from 'style-dictionary/types';

import { cssVarName, getThemeTokens, PACKAGE_ROOT, type Theme } from './sd.config.ts';

const DIST = join(PACKAGE_ROOT, 'dist');

type FlatTokens = Record<string, string | number>;
type NestedTree = Record<string, unknown>;

function tokenValue(token: TransformedToken): string | number {
  const value: unknown = token.$value;
  return typeof value === 'number' ? value : String(value);
}

function flatten(tokens: readonly TransformedToken[]): FlatTokens {
  const flat: FlatTokens = {};
  for (const token of tokens) {
    flat[cssVarName(token.path)] = tokenValue(token);
  }
  return flat;
}

/** Rebuild the DTCG tree from resolved paths (aliases already computed). */
function nest(tokens: readonly TransformedToken[]): NestedTree {
  const root: NestedTree = {};
  for (const token of tokens) {
    const leaf = token.path.at(-1);
    if (!leaf) continue;
    let node = root;
    for (const segment of token.path.slice(0, -1)) {
      const child = node[segment];
      if (typeof child !== 'object' || child === null) {
        node[segment] = {};
      }
      node = node[segment] as NestedTree;
    }
    node[leaf] = token.$value;
  }
  return root;
}

function literal(value: string | number): string {
  return typeof value === 'number' ? String(value) : `'${value.replaceAll("'", "\\'")}'`;
}

function renderObject(record: FlatTokens, indent = ''): string {
  const body = Object.entries(record)
    .map(([name, value]) => `${indent}  '${name}': ${literal(value)},`)
    .join('\n');
  return `{\n${body}\n${indent}}`;
}

function renderTypescript(light: FlatTokens, dark: FlatTokens, roles: readonly string[]): string {
  return `/**
 * Beach Sports DS — generated by @beachsports/tokens.
 * Do not edit by hand: change the DTCG sources in \`src/\` and rebuild.
 */
export const tokens = ${renderObject(light)} as const;

export const darkTokens = ${renderObject(dark)} as const;

export const semanticColorRoles = [
${roles.map((role) => `  '${role}',`).join('\n')}
] as const;

export type TokenName = keyof typeof tokens;
export type DarkTokenName = keyof typeof darkTokens;
export type SemanticColorRole = (typeof semanticColorRoles)[number];
`;
}

function renderDeclarations(record: FlatTokens): string {
  const body = Object.entries(record)
    .map(([name, value]) => `  readonly '${name}': ${literal(value)};`)
    .join('\n');
  return `{\n${body}\n}`;
}

function renderTypes(light: FlatTokens, dark: FlatTokens, roles: readonly string[]): string {
  return `/**
 * Beach Sports DS — generated by @beachsports/tokens.
 * Do not edit by hand: change the DTCG sources in \`src/\` and rebuild.
 */
export declare const tokens: ${renderDeclarations(light)};

export declare const darkTokens: ${renderDeclarations(dark)};

export declare const semanticColorRoles: readonly [
${roles.map((role) => `  '${role}',`).join('\n')}
];

export type TokenName = keyof typeof tokens;
export type DarkTokenName = keyof typeof darkTokens;
export type SemanticColorRole = (typeof semanticColorRoles)[number];
`;
}

function renderJavascript(light: FlatTokens, dark: FlatTokens, roles: readonly string[]): string {
  return `/**
 * Beach Sports DS — generated by @beachsports/tokens.
 * Do not edit by hand: change the DTCG sources in \`src/\` and rebuild.
 */
export const tokens = ${renderObject(light)};

export const darkTokens = ${renderObject(dark)};

export const semanticColorRoles = [
${roles.map((role) => `  '${role}',`).join('\n')}
];
`;
}

async function build(): Promise<void> {
  await rm(DIST, { recursive: true, force: true });
  await mkdir(join(DIST, 'css'), { recursive: true });
  await mkdir(join(DIST, 'ts'), { recursive: true });
  await mkdir(join(DIST, 'json'), { recursive: true });

  const themes: Record<Theme, TransformedToken[]> = {
    light: await getThemeTokens('light'),
    dark: await getThemeTokens('dark'),
  };

  const lightCss = await readFile(join(DIST, 'css', 'tokens.light.css'), 'utf8');
  const darkCss = await readFile(join(DIST, 'css', 'tokens.dark.css'), 'utf8');

  const css = [
    '/**',
    ' * Beach Sports DS — design tokens.',
    ' * Generated by @beachsports/tokens from the DTCG sources. Do not edit by hand.',
    ' * Light is the default (:root). Dark is opt-in via [data-theme="dark"] on <html>.',
    ' */',
    '',
    lightCss.trimEnd(),
    '',
    darkCss.trimEnd(),
    '',
  ].join('\n');

  await writeFile(join(DIST, 'css', 'tokens.css'), css, 'utf8');
  await rm(join(DIST, 'css', 'tokens.light.css'));
  await rm(join(DIST, 'css', 'tokens.dark.css'));

  const lightTokens = themes.light.filter((token) => token.path[0] !== 'color');
  const colorLight = flatten(themes.light.filter((token) => token.path[0] === 'color'));
  const colorDark = flatten(themes.dark.filter((token) => token.path[0] === 'color'));

  const roles = themes.light
    .filter((token) => token.path[0] === 'color')
    .map((token) => token.path.slice(1).join('-'));

  const allLight = flatten(themes.light);
  const allDark = flatten(themes.dark);

  await writeFile(
    join(DIST, 'ts', 'tokens.ts'),
    renderTypescript(allLight, allDark, roles),
    'utf8',
  );
  await writeFile(join(DIST, 'ts', 'tokens.d.ts'), renderTypes(allLight, allDark, roles), 'utf8');
  await writeFile(
    join(DIST, 'ts', 'tokens.js'),
    renderJavascript(allLight, allDark, roles),
    'utf8',
  );

  const resolved = {
    $description:
      'Beach Sports DS — resolved token tree. Aliases are already computed; color roles are split by theme because they share the same paths.',
    ...nest(lightTokens),
    color: {
      light: nest(themes.light.filter((token) => token.path[0] === 'color')),
      dark: nest(themes.dark.filter((token) => token.path[0] === 'color')),
    },
  } as const;

  await writeFile(
    join(DIST, 'json', 'resolved.json'),
    `${JSON.stringify(resolved, null, 2)}\n`,
    'utf8',
  );

  const colorCounts = `light=${Object.keys(colorLight).length}, dark=${Object.keys(colorDark).length}`;
  console.log(
    `tokens: ${Object.keys(allLight).length} light variables (${colorCounts} color roles)`,
  );
  console.log(`tokens: wrote dist/css, dist/ts, dist/json`);
}

await build();
